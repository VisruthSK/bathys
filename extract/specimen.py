"""Publish the compiled font's catalogue to the live HTML proof."""

import json
from pathlib import Path

from outlines import DLIGS, GLYPHS, LIGS

ROOT = Path(__file__).resolve().parent.parent


def write_proof_data():
    chains = sorted(
        {left + pair[1] for left in LIGS for pair in LIGS if left[-1] == pair[0]}
    )
    data = {
        "version": "1.600",
        "glyphCount": len(GLYPHS),
        "standard": list(LIGS),
        "optional": list(DLIGS),
        "chains": chains,
        "alphabet": "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "figures": "0123456789",
    }
    (ROOT / "proof-data.js").write_text(
        "// Generated by extract/build.py; edit the outline catalogue.\n"
        + "const BATHYS_PROOF = "
        + json.dumps(data, indent=2)
        + ";\n",
        encoding="utf-8",
        newline="\n",
    )
